const BENGALI_DIGITS: { [key: string]: string } = {
  '0': '০',
  '1': '১',
  '2': '২',
  '3': '৩',
  '4': '৪',
  '5': '৫',
  '6': '৬',
  '7': '৭',
  '8': '৮',
  '9': '৯',
};

export function toBengaliDigits(val: number | string): string {
  return String(val)
    .split('')
    .map((char) => BENGALI_DIGITS[char] ?? char)
    .join('');
}

export function getPersonality(score: number): Personality {
  const boundedScore = Math.max(0, Math.min(100, Math.round(score)));
  const match = PERSONALITIES.find(
    (p) => boundedScore >= p.minScore && boundedScore <= p.maxScore
  );
  return match ?? PERSONALITIES[PERSONALITIES.length - 1];
}
